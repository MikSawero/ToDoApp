function getCurrentLang() {
    return localStorage.getItem('app_lang') || 'pl';
}

function setCurrentLang(lang) {
    localStorage.setItem('app_lang', lang);
    applyTranslations();
}

function t(key) {
    const lang = getCurrentLang();
    return translations[lang][key] || key;
}

function applyTranslations() {
    const lang = getCurrentLang();
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerText = translations[lang][key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    const dayHeaders = document.querySelectorAll('.calendar-day-name');
    if (dayHeaders.length === 7) {
        dayHeaders.forEach((el, idx) => {
            el.innerText = translations[lang].days_short[idx];
        });
    }

    const switcher = document.getElementById('lang-switcher');
    if (switcher) {
        switcher.value = lang;
    }
    const settingsLangSelect = document.getElementById('settings-lang-select');
    if (settingsLangSelect) {
        settingsLangSelect.value = lang;
    }
    applyTheme();
}

function getCurrentTheme() {
    return localStorage.getItem('app_theme') || 'light';
}

function setCurrentTheme(theme) {
    localStorage.setItem('app_theme', theme);
    applyTheme();
}

function applyTheme() {
    const theme = getCurrentTheme();
    document.documentElement.setAttribute('data-theme', theme);
    if (document.body) {
        document.body.setAttribute('data-theme', theme);
    }
    const themeSelect = document.getElementById('settings-theme-select');
    if (themeSelect) {
        themeSelect.value = theme;
    }
}

function getAutoDeleteDays() {
    return localStorage.getItem('app_auto_delete_days') || 'never';
}

function setAutoDeleteDays(val) {
    localStorage.setItem('app_auto_delete_days', String(val));
}

async function cleanupExpiredEvents(eventsList, token) {
    const setting = getAutoDeleteDays();
    if (setting === 'never' || setting === null || setting === '') {
        return eventsList;
    }
    const maxDays = Number(setting);
    if (Number.isNaN(maxDays)) {
        return eventsList;
    }

    const today = new Date();
    today.setHours(0, 0, 0, 0);

    const remaining = [];
    const toDelete = [];

    for (const ev of eventsList) {
        if (!ev.date) {
            remaining.push(ev);
            continue;
        }
        const target = new Date(ev.date);
        target.setHours(0, 0, 0, 0);
        const diffDaysAgo = Math.floor((today - target) / (1000 * 60 * 60 * 24));
        if (diffDaysAgo > maxDays) {
            toDelete.push(ev);
        } else {
            remaining.push(ev);
        }
    }

    for (const ev of toDelete) {
        try {
            await fetch(`http://localhost:8000/api/v1/events/${ev.id}`, {
                method: 'DELETE',
                headers: { 'Authorization': `Bearer ${token}` }
            });
        } catch (err) {
            console.error(err);
        }
    }

    return remaining;
}